void HardFault_Decode(uint32_t *stack)
{
    volatile uint32_t r0   = stack[0];
    volatile uint32_t r1   = stack[1];
    volatile uint32_t r2   = stack[2];
    volatile uint32_t r3   = stack[3];
    volatile uint32_t r12  = stack[4];
    volatile uint32_t lr   = stack[5];  // link register — where the fault came from
    volatile uint32_t pc   = stack[6];  // program counter — the faulting instruction
    volatile uint32_t xpsr = stack[7];

    // Fault status registers
    volatile uint32_t CFSR  = SCB->CFSR;   // Configurable Fault Status
    volatile uint32_t HFSR  = SCB->HFSR;   // HardFault Status
    volatile uint32_t DFSR  = SCB->DFSR;   // Debug Fault Status
    volatile uint32_t AFSR  = SCB->AFSR;   // Auxiliary Fault Status
    volatile uint32_t BFAR  = SCB->BFAR;   // Bus Fault Address (if BFARVALID set)
    volatile uint32_t MMAR  = SCB->MMFAR;  // MemManage Fault Address

    (void)r0; (void)r1; (void)r2; (void)r3;
    (void)r12; (void)lr; (void)pc; (void)xpsr;
    (void)CFSR; (void)HFSR; (void)DFSR;
    (void)AFSR; (void)BFAR; (void)MMAR;

    __disable_irq();
    // Set a breakpoint here and inspect all the volatile variables above
    // in your debugger's "Variables" or "Expressions" window
    while(1);
}
